"""Layer 3 — gas physics per cell: n_H, T, ion fractions and ion densities (JAX).

Everything here is a pure function of per-cell arrays (jit / vmap / grad friendly), except the
reading of tables from disk.

Conventions and choices (each is justified and quantified in
``step_by_step_comparison_fake_spectra.ipynb``, Sec. 4):

* **Mass unit.** n_X = rho X_X / (A_X m_u), with A_X the standard atomic weight
  (``lines_table.dat``) and m_u = 1.66053906660e-24 g the atomic mass unit (default,
  ``mass_unit="amu"``). fake_spectra divides by A_X m_p (``mass_unit="proton"``), which is
  0.728 % heavier (m_p / m_u = 1.00728) because m_p is not an atomic mass unit
  (``absorption.h`` L4 labels PROTONMASS "1 a.m.u").
* **Temperature.** T = (gamma - 1) mu m_p u / k_B, mu = 4 / (1 + 3 X + 4 X n_e), X = 0.76 (TNG FAQ;
  fake_spectra ``abstractsnapshot.get_temp`` L121-L154). ``constants="codata"`` uses CODATA 2018
  m_p and k_B; ``"fake_spectra"`` uses fake_spectra's ``unitsystem.py`` values (m_p 1.67262178e-24,
  k_B 1.38066e-16), which makes T 8.1e-6 lower.
* **H I fraction.** ``x_HI_model="stored_sf"`` (default) keeps TNG's ``NeutralHydrogenAbundance``,
  which Arepo computes on the fly in ionisation equilibrium with the FG09 (``TREECOOL_fg_dec11``)
  UVB, the Rahmati+13 self-shielding factor and the local AGN radiation (Vogelsberger+13
  Sec. 2.4, 2.4.1; TNG header ``UVB_SELF_SHIELDING``, ``SelfShieldingFile``,
  ``GFM_AGN_RADIATION``). Only star-forming cells (SFR > 0, effective equation of state, whose
  stored x_HI "is based on the effective temperature", TNG data specifications) are recomputed:
  Rahmati+13 at T = 1e4 K, i.e. the cold phase, with the simulation's own UVB.
  ``"stored"`` keeps every cell; ``"fake_sf"`` is fake_spectra's ``sf_neutral=True`` rule
  (``gas_properties.get_reproc_HI`` L116-L146: rho/m_p > n_thr/0.76, FG09 table Gamma, n = rho/m_p);
  ``"rahmati_all"`` is the previous SkewerJAX default (``TNGSimulation.apply_rahmati_HI_correction``,
  every cell), kept only for comparison.
* **Metal ion fractions.** CLOUDY tables (``cloudy_tables/ion_out_photo_atten``: FG11 UVB with
  Rahmati attenuation, GASS10 1/10 solar, generated by ``make_cloudy_input.py``). CLOUDY's
  ``hden`` is the hydrogen density, so the default passes the cell's n_H
  (``cloudy_density="hydrogen"``). fake_spectra passes rho/m_p, which ``CloudyTable.ion``
  multiplies by 0.774132 (``convert_cloudy.py`` L183): ``"fake_spectra"``. The default
  interpolation is bilinear in (log hden, log T) of log f (``jax.scipy.ndimage.map_coordinates``,
  order 1); ``interpolation="cubic"`` reproduces ``CloudyTable.ion`` (scipy cubic B-spline, order 3),
  which overshoots near the -30 "log 0" floor of the table. The table is read directly
  (``CloudyIonTable``): no fake_spectra-derived code runs in SkewerJAX.
"""
from __future__ import annotations

from pathlib import Path
from typing import Optional

import numpy as np
import jax.numpy as jnp
from jax.scipy.ndimage import map_coordinates

from skewerjax.constants.lines import get_mass_amu
from skewerjax.constants.physical_constants import phys

# ---------------------------------------------------------------------------- constants
M_U_G = 1.0 / phys.g_to_amu                       # atomic mass unit [g]
CONSTANTS = {                                      # (m_p [g], k_B [erg/K]) used in T
    "codata": (phys.mp, phys.kB_erg_per_K),
    "fake_spectra": (1.67262178e-24, 1.38066e-16),  # fake_spectra unitsystem.py L21, L23
}
# fake_spectra's C engine (absorption.h L4, absorption.cpp L158): b = sqrt(2 k T / (A m_p))
FAKE_C_BOLTZMANN, FAKE_C_PROTONMASS = 1.3806504e-16, 1.67262178e-24
FAKE_SPECTRA_B2_RATIO = (FAKE_C_BOLTZMANN / FAKE_C_PROTONMASS) / (phys.kB_erg_per_K / M_U_G)
"""(b_fake / b_SkewerJAX)^2 at equal T and A: fake_spectra's (k_B / m_p) over SkewerJAX's
(k_B / m_u) = 0.992777. Multiplying T by it inside the profile reproduces fake_spectra's b."""
CLOUDY_HDEN_FACTOR = 0.774132                     # convert_cloudy.CloudyTable.ion, rho *= 0.774132
GFM_METALS_ORDER = ("H", "He", "C", "N", "O", "Ne", "Mg", "Si", "Fe")
_ROMAN = ("I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X")


class Ion:
    """An absorbing ion, e.g. ``Ion("H", 1)`` (H I) or ``Ion("Si", 3)`` (Si III).

    The only ion-specific inputs of the whole pipeline are its element mass fraction column,
    its atomic weight and its ionisation model; everything geometric is shared.
    """

    def __init__(self, element: str, stage: int):
        if element not in GFM_METALS_ORDER:
            raise ValueError(f"element must be one of {GFM_METALS_ORDER}, got {element!r}.")
        if not 1 <= int(stage) <= len(_ROMAN):
            raise ValueError(f"stage must be in [1, {len(_ROMAN)}], got {stage!r}.")
        self.element, self.stage = element, int(stage)

    def __repr__(self):
        return f"Ion({self.element!r}, {self.stage})"

    @property
    def species(self) -> str:
        """Token of ``lines_table.dat`` ("HI", "SiIII", ...)."""
        return f"{self.element}{_ROMAN[self.stage - 1]}"

    @property
    def metals_column(self) -> int:
        return GFM_METALS_ORDER.index(self.element)

    @property
    def mass_amu(self) -> float:
        return float(get_mass_amu([self.element])[self.element])

    @property
    def is_HI(self) -> bool:
        return self.element == "H" and self.stage == 1


HI = Ion("H", 1)


# ---------------------------------------------------------------------------- densities, T, b
def _mass_unit_g(mass_unit: str) -> float:
    if mass_unit == "amu":
        return M_U_G
    if mass_unit == "proton":
        return phys.mp
    raise ValueError(f"mass_unit must be 'amu' or 'proton', got {mass_unit!r}.")


def element_number_density(rho, mass_fraction, mass_amu: float, mass_unit: str = "amu"):
    """n_X = rho X / (A m) [physical cm^-3]; rho [g cm^-3]."""
    return jnp.asarray(rho) * jnp.asarray(mass_fraction) / (mass_amu * _mass_unit_g(mass_unit))


def temperature(u, n_e, *, X: float = 0.76, gamma: float = 5.0 / 3.0, constants: str = "codata"):
    """T [K] from the specific internal energy u [erg/g] and n_e / n_H; T <= 0 -> 1 K
    (fake_spectra ``spectra.py`` L608-L611)."""
    m_p, k_B = CONSTANTS[constants]
    mu = 4.0 / (1.0 + 3.0 * X + 4.0 * X * jnp.asarray(n_e))
    T = (gamma - 1.0) * mu * m_p / k_B * jnp.asarray(u)
    return jnp.where(T > 0, T, 1.0)


def doppler_b_kms(T, mass_amu: float):
    """Thermal Doppler parameter b = sqrt(2 k_B T / (A m_u)) [km/s] (``line_profile.py`` L390)."""
    return jnp.sqrt(2.0 * phys.kB * jnp.asarray(T) / mass_amu) / 1e3


# ---------------------------------------------------------------------------- UVB and H I
def treecool_rates(redshift: float, path) -> dict:
    """Photoionisation rates of H I, He I, He II [s^-1] from a TREECOOL file (columns
    log10(1+z), Gamma_HI, Gamma_HeI, Gamma_HeII, heating rates), interpolated linearly in
    log10(1+z) and log10(Gamma), as Arepo does."""
    t = np.loadtxt(path)
    lz = np.log10(1.0 + redshift)
    if not t[0, 0] <= lz <= t[-1, 0]:
        raise ValueError(f"z = {redshift} outside the TREECOOL table {path}.")
    g = [10 ** np.interp(lz, t[:, 0], np.log10(np.maximum(t[:, c], 1e-300))) for c in (1, 2, 3)]
    return dict(Gamma_HI=g[0], Gamma_HeI=g[1], Gamma_HeII=g[2])


def default_treecool_path() -> Path:
    """The FG09 Dec-2011 update used by TNG (``TreecoolFile = TREECOOL_fg_dec11``)."""
    from skewerjax.simulations.simulations import get_default_cloudy_table_dir
    return Path(get_default_cloudy_table_dir()).parent / "UVB_tables" / "TREECOOL_fg_dec11"


# Rahmati+12 (MNRAS 430, 2427) Table 2 / fake_spectra gas_properties.py L44-L46: FG09 Gamma and
# gray opacity at z = 0..8 (used for n_SSh in their Eq. 13).
_RAHMATI_Z = np.arange(9.0)
_RAHMATI_GAMMA_FG09 = np.array([3.99e-14, 3.03e-13, 6e-13, 5.53e-13, 4.31e-13, 3.52e-13, 2.678e-13, 1.81e-13, 9.43e-14])
_RAHMATI_GRAY = np.array([2.59e-18, 2.37e-18, 2.27e-18, 2.15e-18, 2.02e-18, 1.94e-18, 1.82e-18, 1.71e-18, 1.60e-18])


def rahmati_neutral_fraction(n_H, T, redshift: float, *, gamma_uvb: Optional[float] = None,
                             f_bar: float = 0.17):
    """Rahmati+13 photoionisation-equilibrium x_HI with self-shielding (their Eqs. 13-14, A8;
    fake_spectra ``gas_properties._neutral_fraction`` L92-L99).

    The quadratic assumes n_e = n_HII (no helium electrons) and the Hui & Gnedin (1997) case-A
    recombination rate. ``gamma_uvb`` None takes the FG09 value of Rahmati's table.
    """
    n_H, T = jnp.asarray(n_H), jnp.maximum(jnp.asarray(T), 1.0)
    g_tab = float(np.interp(redshift, _RAHMATI_Z, _RAHMATI_GAMMA_FG09))
    gamma = g_tab if gamma_uvb is None else float(gamma_uvb)
    gray = float(np.interp(redshift, _RAHMATI_Z, _RAHMATI_GRAY))
    n_ssh = 6.73e-3 * (gray / 2.49e-18) ** (-2.0 / 3.0) * (T / 1e4) ** 0.17 * (gamma / 1e-12) ** (2.0 / 3.0) \
        * (f_bar / 0.17) ** (-1.0 / 3.0)
    y = n_H / n_ssh
    photo = gamma * (0.98 * (1.0 + y ** 1.64) ** -2.28 + 0.02 * (1.0 + y) ** -0.84)
    lam = 315614.0 / T
    alpha_A = 1.269e-13 * lam ** 1.503 / (1.0 + (lam / 0.522) ** 0.47) ** 1.923
    coll = 1.17e-10 * jnp.sqrt(T) * jnp.exp(-157809.0 / T) / (1.0 + jnp.sqrt(T / 1e5))
    A = alpha_A + coll
    B = 2.0 * alpha_A + photo / jnp.maximum(n_H, 1e-300) + coll
    return jnp.clip((B - jnp.sqrt(jnp.maximum(B * B - 4.0 * A * alpha_A, 0.0))) / (2.0 * A), 0.0, 1.0)


def arepo_equilibrium_neutral_fraction(n_H, T, n_e, gamma_HI: float, shielding=1.0):
    """Arepo's ionisation equilibrium for H I (Katz+96 Eq. 33 with Cen 1992 rates, Vogelsberger+13
    Sec. 2.4): x_HI = alpha / (alpha + Gamma_e + Gamma_HI S / n_e), with n_e = ``n_e`` x n_H the
    stored electron density and S the self-shielding factor. Used to *check* the stored values."""
    n_H, T = jnp.asarray(n_H), jnp.maximum(jnp.asarray(T), 1.0)
    alpha = 8.4e-11 / jnp.sqrt(T) / (T / 1e3) ** 0.2 / (1.0 + (T / 1e6) ** 0.7)
    coll = 5.85e-11 * jnp.sqrt(T) * jnp.exp(-157809.1 / T) / (1.0 + jnp.sqrt(T / 1e5))
    ne = jnp.maximum(jnp.asarray(n_e) * n_H, 1e-300)
    return alpha / (alpha + coll + gamma_HI * shielding / ne)


def neutral_fraction(cells, n_H, T, *, model: str = "stored_sf", redshift: float,
                     gamma_HI: Optional[float] = None, f_bar: float = 0.17):
    """x_HI per cell for the H I ionisation ``model`` (see module docstring).

    Parameters
    ----------
    cells : GasCells with fields ``x_HI_stored``, ``sfr`` and ``rho`` as required.
    n_H, T : per-cell hydrogen density [cm^-3] and temperature [K].
    gamma_HI : H I photoionisation rate of the simulation's UVB [s^-1] for ``"stored_sf"``; None
        reads ``TREECOOL_fg_dec11`` at ``redshift``.
    """
    stored = jnp.asarray(cells.fields["x_HI_stored"]) if "x_HI_stored" in cells.fields else None
    if model == "stored":
        return stored
    if model == "stored_sf":
        if gamma_HI is None:
            gamma_HI = treecool_rates(redshift, default_treecool_path())["Gamma_HI"]
        sf = jnp.asarray(cells.fields["sfr"]) > 0
        x_cold = rahmati_neutral_fraction(n_H, 1e4 * jnp.ones_like(n_H), redshift, gamma_uvb=gamma_HI, f_bar=f_bar)
        return jnp.where(sf, x_cold, stored)
    if model == "fake_sf":
        rho_mp = jnp.asarray(cells.fields["rho"]) / CONSTANTS["fake_spectra"][0]
        thr = fake_spectra_sf_threshold()
        x_cold = rahmati_neutral_fraction(rho_mp, 1e4 * jnp.ones_like(rho_mp), redshift, f_bar=f_bar)
        return jnp.where(rho_mp > thr / 0.76, x_cold, stored)
    if model == "rahmati_all":
        x = rahmati_neutral_fraction(n_H, T, redshift, f_bar=f_bar)
        sf = jnp.asarray(cells.fields["sfr"]) > 0
        return jnp.where(sf, rahmati_neutral_fraction(n_H, 1e4 * jnp.ones_like(n_H), redshift, f_bar=f_bar), x)
    raise ValueError(f"unknown x_HI model {model!r}; use 'stored_sf', 'stored', 'fake_sf' or 'rahmati_all'.")


def fake_spectra_sf_threshold(h: float = 0.6774, t_0_star=2.27, T_SN=5.73e7, T_c=1000.0, A_0=573.0) -> float:
    """Star-formation threshold in H atoms / cm^3 as fake_spectra computes it
    (``gas_properties._get_rho_thresh`` L148-L200, TNG parameters MaxSfrTimescale, TempSupernova,
    TempClouds, FactorEVP); 0.1199 cm^-3 for TNG50."""
    m_p, k_B = 1.67262178e-24, 1.38066e-16
    unit_time = 3.085678e21 / 1e5
    t0 = t_0_star * unit_time / h
    beta, X = 0.264089, 0.76
    u_c = 1.0 / (4 / (1 + 3 * X)) * 1.5 * (k_B / m_p) * T_c
    mw = 4 / (8 - 5 * (1 - X))
    u_SN = 1.0 / mw * 1.5 * (k_B / m_p) * T_SN
    rhoinf = 277.476 * 6.769911178294544e-22 * h ** 2
    tcool = 4.64419e-10 * unit_time / h
    u_h = u_SN / A_0
    u_4 = 1.0 / mw * 1.5 * (k_B / m_p) * 1e4
    x = (u_h - u_4) / (u_h - u_c)
    physdens = x / (1 - x) ** 2 * (beta * u_SN - (1 - beta) * u_c) / (t0 * (u_h / tcool / rhoinf))
    return physdens / m_p * X


# ---------------------------------------------------------------------------- CLOUDY tables
class CloudyIonTable:
    """CLOUDY ion fractions f(hden, T) at one redshift, evaluated in JAX; self-contained.

    Reads the preprocessed table ``<directory>/cloudy_table.npz`` (array ``table`` of shape
    (N_z, 55, 112, 9, 17): redshifts z = 0, 1, ..., log10 hden = -7, -6.8, ..., 3.8, log10 T = 3,
    3.05, ..., 8.55, the elements of ``GFM_METALS_ORDER`` and ion stages 1..17), interpolates it
    linearly in redshift, and evaluates log10 f bilinearly in (log10 hden, log10 T) with
    ``jax.scipy.ndimage.map_coordinates`` (order 1), clamped to the table bounds (as fake_spectra,
    ``spectra.py`` L683-L698). ``interpolation="cubic"`` reproduces fake_spectra's
    ``CloudyTable.ion`` (scipy cubic B-spline, ``mode="nearest"``) on the host, for comparisons.

    The table itself was produced by ``cloudy_tables/make_cloudy_input.py`` (FG UVB ``fg_uvb_dec11``,
    attenuated above 13.6 eV by the Rahmati+13 self-shielding factor, GASS10 abundances at 1/10
    solar) and is byte-identical to fake_spectra's ``cloudy_tables/ion_out_photo_atten``.
    """

    LOG_DENS = np.arange(-7.0, 4.0, 0.2)
    LOG_TEMP = np.arange(3.0, 8.6, 0.05)

    def __init__(self, redshift: float, directory=None):
        if directory is None:
            from skewerjax.simulations.simulations import get_default_cloudy_table_dir
            directory = get_default_cloudy_table_dir()
        table = np.load(Path(directory) / "cloudy_table.npz")["table"]
        if table.shape[1:3] != (self.LOG_DENS.size, self.LOG_TEMP.size):
            raise ValueError(f"unexpected CLOUDY table shape {table.shape}")
        reds = np.arange(table.shape[0], dtype=np.float64)
        z = 4.0 if 4.0 < redshift < 4.1 else float(redshift)          # convert_cloudy's round-off guard
        if not reds[0] <= z <= reds[-1]:
            raise ValueError(f"z = {redshift} outside the table range [{reds[0]}, {reds[-1]}].")
        j = min(int(np.floor(z)), reds.size - 2)
        w = z - reds[j]
        self.red_table = (1.0 - w) * table[j] + w * table[j + 1]          # (55, 112, 9, 17) log10 f
        self.log_dens, self.log_temp = self.LOG_DENS, self.LOG_TEMP
        self.redshift = float(redshift)

    def log_fraction_grid(self, ion: Ion) -> np.ndarray:
        """(N_dens, N_temp) log10 f of ``ion`` at the table redshift."""
        return np.asarray(self.red_table[:, :, GFM_METALS_ORDER.index(ion.element), ion.stage - 1], dtype=np.float64)

    def _coords(self, hden, T, xp, clamp_density: bool = True):
        ld, lt = self.log_dens, self.log_temp
        hden = xp.clip(hden, 10 ** ld[0], 10 ** ld[-1]) if clamp_density else hden
        x = (xp.log10(hden) - ld[0]) / (ld[1] - ld[0])
        y = (xp.log10(xp.clip(T, 10 ** lt[0], 10 ** lt[-1])) - lt[0]) / (lt[1] - lt[0])
        return x, y

    def fraction(self, ion: Ion, hden, T, *, interpolation: str = "linear"):
        """Ion fraction f = n_ion / n_element for hydrogen density ``hden`` [cm^-3] and T [K]."""
        if interpolation == "cubic":
            from scipy.ndimage import map_coordinates as map_coordinates_np
            # as CloudyTable.ion: the density coordinate is not clamped (callers clamp rho / m_p before
            # the x 0.774132), points off the grid take mode="nearest"
            x, y = self._coords(np.asarray(hden, dtype=np.float64), np.asarray(T, dtype=np.float64), np, clamp_density=False)
            return jnp.asarray(10.0 ** map_coordinates_np(self.log_fraction_grid(ion), np.vstack([x, y]), mode="nearest"))
        if interpolation != "linear":
            raise ValueError(f"interpolation must be 'linear' or 'cubic', got {interpolation!r}.")
        x, y = self._coords(jnp.asarray(hden), jnp.asarray(T), jnp)
        return 10.0 ** map_coordinates(jnp.asarray(self.log_fraction_grid(ion)), [x, y], order=1, mode="nearest")


# ---------------------------------------------------------------------------- per-ion densities
def ion_properties(cells, ion: Ion, *, mass_unit: str = "amu", T_constants: str = "codata",
                   x_HI_model: str = "stored_sf", cloudy: Optional[CloudyIonTable] = None,
                   cloudy_density: str = "hydrogen", cloudy_interpolation: str = "linear",
                   X_mu: float = 0.76, gamma_HI: Optional[float] = None, f_bar: float = 0.17) -> dict:
    """Per-cell n_H, T, ion fraction and ion density for ``ion`` (one code path for every ion).

    Returns
    -------
    dict of (N,) arrays: ``n_H`` [cm^-3], ``T`` [K], ``ion_fraction``, ``n_elem``, ``n_ion``
    [physical cm^-3 at the snapshot epoch]; plus ``mass_amu`` and ``species``.
    """
    f = cells.fields
    redshift = 1.0 / cells.a - 1.0
    rho = jnp.asarray(f["rho"])
    metals = jnp.asarray(f["metals"])
    n_H = element_number_density(rho, metals[:, 0], get_mass_amu(["H"])["H"], mass_unit)
    T = temperature(f["u"], f["n_e"], X=X_mu, constants=T_constants)
    if ion.is_HI:
        frac = neutral_fraction(cells, n_H, T, model=x_HI_model, redshift=redshift, gamma_HI=gamma_HI, f_bar=f_bar)
    else:
        if cloudy is None:
            cloudy = CloudyIonTable(redshift)
        if cloudy_density == "hydrogen":
            hden = n_H
        elif cloudy_density == "fake_spectra":             # rho/m_p, clamped, then x 0.774132 (spectra.py L691-L698, convert_cloudy L183)
            rho_atoms = jnp.clip(rho / CONSTANTS["fake_spectra"][0], 10 ** CloudyIonTable.LOG_DENS[0], 10 ** CloudyIonTable.LOG_DENS[-1])
            hden = CLOUDY_HDEN_FACTOR * rho_atoms
        else:
            raise ValueError(f"cloudy_density must be 'hydrogen' or 'fake_spectra', got {cloudy_density!r}.")
        frac = cloudy.fraction(ion, hden, T, interpolation=cloudy_interpolation)
    n_elem = element_number_density(rho, metals[:, ion.metals_column], ion.mass_amu, mass_unit)
    return dict(n_H=n_H, T=T, ion_fraction=frac, n_elem=n_elem, n_ion=n_elem * frac,
                mass_amu=ion.mass_amu, species=ion.species)
